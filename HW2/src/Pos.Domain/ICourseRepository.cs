namespace Pos.Domain;

// Порт хранилища: доменная модель работает с курсом и не зависит от JSON, путей и консоли.
public interface ICourseRepository
{
    // Возвращает независимое состояние курса из хранилища; при отсутствии сохранённых данных — пустой курс.
    Course Load();

    // Сохраняет текущее состояние всего агрегата курса.
    void Save(Course course);
}
